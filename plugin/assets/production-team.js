/* global SyndaMorphTeam */
( function () {
    'use strict';
    const byId = ( id ) => document.getElementById( id );
    const job = byId( 'syndamorph-team-job' );
    const source = byId( 'syndamorph-team-source' );
    const brief = byId( 'syndamorph-team-brief' );
    const run = byId( 'syndamorph-team-run' );
    const reset = byId( 'syndamorph-team-reset' );
    const timeline = byId( 'syndamorph-team-timeline' );
    const review = byId( 'syndamorph-team-review' );
    const jobState = byId( 'syndamorph-team-job-state' );
    const handoffs = byId( 'syndamorph-team-handoffs' );
    const outputState = byId( 'syndamorph-team-output-state' );
    const notice = byId( 'syndamorph-team-validation' );
    if ( !job || !run || !timeline ) return;

    // An intentional, synchronous UI-only simulation; no network or inference.
    const stages = [
        { agent: 'boss', name: 'Boss Agent', action: 'Classify and delegate', message: 'Accepted the demonstration brief and assigned design planning.' },
        { agent: 'designer', name: 'Designer Agent', action: 'Design handoff', message: 'Acknowledged design planning. Section architecture would be prepared during a real run.' },
        { agent: 'developer', name: 'Developer Agent', action: 'Implementation handoff', message: 'Acknowledged implementation. No Gutenberg code or artifacts were generated.' },
        { agent: 'boss', name: 'Boss Agent', action: 'Review and close', message: 'Recorded all communication steps. Workflow simulation complete; actual deliverables remain pending.' },
    ];

    function setAgentStates( completed ) {
        document.querySelectorAll( '#syndamorph-production-team [data-agent]' ).forEach( ( node ) => {
            const pill = node.querySelector( '.sm-status-pill' );
            const done = stages.slice( 0, completed ).some( step => step.agent === node.dataset.agent );
            pill.textContent = done ? 'Acknowledged' : 'Standing by';
            pill.dataset.state = done ? 'success' : 'idle';
        } );
    }
    function setText( node, text ) { if ( node ) node.textContent = text; }
    function clear() {
        timeline.replaceChildren();
        const empty = document.createElement( 'li' );
        empty.className = 'sm-team-empty';
        empty.textContent = 'No activity yet. Run a simulation to view agent handoffs.';
        timeline.append( empty );
        review.replaceChildren();
        const heading = document.createElement( 'strong' );
        heading.textContent = 'No output available';
        const body = document.createElement( 'p' );
        body.textContent = 'Complete a simulation to review its handoff summary. Gutenberg patterns, HTML, and custom blocks are not generated by this mode.';
        review.append( heading, body );
        setText( jobState, 'Not started' );
        setText( handoffs, '00 / 04' );
        setText( outputState, 'Not generated' );
        setText( notice, 'Local simulation only · no AI tokens consumed.' );
        setAgentStates( 0 );
    }
    run.addEventListener( 'click', () => {
        const title = job.value.trim();
        if ( !title ) {
            notice.textContent = 'Enter a job title to start the demonstration.';
            job.focus();
            return;
        }
        if ( source.value.trim() ) {
            try {
                const url = new URL( source.value.trim() );
                if ( ![ 'http:', 'https:' ].includes( url.protocol ) ) throw new Error( 'Invalid scheme' );
            } catch ( _error ) {
                notice.textContent = 'Source reference must be a valid HTTP(S) URL or remain empty.';
                source.focus();
                return;
            }
        }
        timeline.replaceChildren();
        stages.forEach( ( stage, index ) => {
            const item = document.createElement( 'li' );
            item.className = 'sm-team-step';
            const title = document.createElement( 'strong' );
            title.textContent = ( index + 1 ) + '. ' + stage.name + ' — ' + stage.action;
            const text = document.createElement( 'p' );
            text.textContent = stage.message;
            item.append( title, text );
            timeline.append( item );
        } );
        review.replaceChildren();
        const heading = document.createElement( 'strong' );
        heading.textContent = 'Workflow simulation complete';
        const summary = document.createElement( 'p' );
        summary.textContent = 'Job: ' + title + '. All four predefined communication steps completed. ' +
            ( brief.value.trim() ? 'Brief recorded for this browser session only. ' : '' ) +
            'No source was captured and no Gutenberg deliverables were generated.';
        review.append( heading, summary );
        setText( jobState, 'Simulated' );
        setText( handoffs, '04 / 04' );
        setText( outputState, 'Not generated' );
        setText( notice, 'Simulation complete · deterministic UI stages · no backend execution.' );
        setAgentStates( 4 );
    } );
    reset.addEventListener( 'click', clear );

    const purrRun = byId( 'syndamorph-purr-run' );
    const purrState = byId( 'syndamorph-purr-status' );
    const purrTranscript = byId( 'syndamorph-purr-transcript' );
    if ( purrRun && purrState && purrTranscript ) {
        purrRun.addEventListener( 'click', async () => {
            if ( purrRun.disabled ) return;
            const title = job.value.trim();
            if ( !title ) {
                notice.textContent = 'Enter a job title before testing Purr.';
                job.focus();
                return;
            }
            purrRun.disabled = true;
            purrState.textContent = 'Connecting';
            purrState.dataset.state = 'running';
            purrTranscript.textContent = 'Opening Purr session and exchanging four messages…';
            try {
                const response = await fetch( SyndaMorphTeam.purrPocUrl, {
                    method: 'POST',
                    credentials: 'same-origin',
                    headers: { 'Content-Type': 'application/json', 'X-WP-Nonce': SyndaMorphTeam.nonce },
                    body: JSON.stringify( { job: title } ),
                } );
                const data = await response.json();
                if ( !response.ok || !data.success || !data.session_created || data.steps_completed !== 4 ||
                     !Array.isArray( data.conversation ) ) {
                    throw new Error( 'Incomplete Purr communication result' );
                }
                purrTranscript.replaceChildren();
                for ( const item of data.conversation ) {
                    const row = document.createElement( 'article' );
                    row.className = 'sm-purr-message';
                    const heading = document.createElement( 'strong' );
                    heading.textContent = item.step + '. ' + item.agent + ' · ' + item.action;
                    const message = document.createElement( 'p' );
                    message.textContent = item.message;
                    row.append( heading, message );
                    purrTranscript.append( row );
                }
                purrState.textContent = '4 / 4 received';
                purrState.dataset.state = 'success';
            } catch ( _error ) {
                purrState.textContent = 'Failed';
                purrState.dataset.state = 'error';
                purrTranscript.textContent = 'Communication test could not complete. Check Purr configuration, Railway availability, and backend connectivity.';
            } finally {
                purrRun.disabled = false;
            }
        } );
    }
} )();
